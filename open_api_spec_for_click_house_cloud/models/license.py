from __future__ import annotations

from uuid import UUID

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, RFC3339DateTime, SdkBaseModel


class License(SdkBaseModel):
    id: Optional[UUID] = UNSET
    """Unique license ID."""

    name: Optional[str] = UNSET
    """User-provided name for the license."""

    expiration: Optional[RFC3339DateTime] = UNSET
    """Expiration timestamp, inherited from the organization's licensing terms. Absent when the organization has no
    licensing terms configured. ISO-8601."""

    memory: Optional[str] = UNSET
    """Memory reserved for license."""

    environment_fingerprint: Optional[str] = Field(default=UNSET, alias="environmentFingerprint")
    """Environment fingerprint generated by private infrastructure."""


class LicenseDict(TypedDict):
    id: NotRequired[UUID]
    name: NotRequired[str]
    expiration: NotRequired[RFC3339DateTime]
    memory: NotRequired[str]
    environment_fingerprint: NotRequired[str]
